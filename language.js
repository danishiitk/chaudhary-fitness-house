(() => {
  const storageKey = 'cfh-language';
  let language = 'en';
  const translate = text => language === 'hi' ? (hindiCopy[text] ?? text) : text;
  const validationMessages = {
    name: 'Please enter your name.',
    phone: 'Please enter your phone number.',
    goal: 'Please select your goal.',
    'contact-consent': 'Please agree to be contacted about your enquiry.',
  };
  const fields = [...document.querySelectorAll('.enquiry-form input:not([type="hidden"]), .enquiry-form select')];
  function validate(field) {
    field.setCustomValidity('');
    if (field.validity.valueMissing) {
      field.setCustomValidity(translate(validationMessages[field.name] || 'Please enter your name.'));
    } else if (field.validity.patternMismatch) {
      field.setCustomValidity(translate('Enter 10 to 15 digits, with an optional country code, spaces, or hyphens.'));
    }
  }
  function applyLanguage(nextLanguage, persist = true) {
    language = nextLanguage === 'hi' ? 'hi' : 'en';
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach(element => {
      element.textContent = translate(element.dataset.i18n);
    });
    for (const attribute of ['aria-label', 'alt', 'placeholder', 'title', 'content']) {
      document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
        element.setAttribute(attribute, translate(element.getAttribute(`data-i18n-${attribute}`)));
      });
    }
    document.querySelectorAll('[data-language]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    const preferredLanguage = document.querySelector('[name="preferred-language"]');
    if (preferredLanguage) preferredLanguage.value = language;
    fields.forEach(field => {
      if (field.validity.customError) validate(field);
    });
    if (persist) {
      try { localStorage.setItem(storageKey, language); } catch { /* Language still works when storage is unavailable. */ }
    }
    document.dispatchEvent(new CustomEvent('languagechange'));
  }
  fields.forEach(field => {
    field.addEventListener('invalid', () => validate(field));
    field.addEventListener('input', () => field.setCustomValidity(''));
    field.addEventListener('change', () => field.setCustomValidity(''));
  });
  window.siteI18n = { translate, get language() { return language; } };
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => applyLanguage(button.dataset.language));
  });
  let savedLanguage;
  try { savedLanguage = localStorage.getItem(storageKey); } catch { /* Default to English. */ }
  applyLanguage(savedLanguage, false);
})();
